function getIcon(href: string, role: string): string | null {
  if (role === "ATHLETE") return ATLET_ICONS[href] ?? null;
  if (role === "PARENT") return PARENT_ICONS[href] ?? null;
  return NAV_ICONS[href] ?? null;
}

export function SidebarNav({
  items,
  role,
}: {
  items: { label: string; href: string }[];
  role: string;
}) {
  const pathname = usePathname();

  return (
    <nav className="flex-1 space-y-1 px-3 py-2">
      {items.map((item) => {
        const isActive =
          item.href === "/pelatih"
            ? pathname === "/pelatih"
            : pathname.startsWith(item.href);
        const iconPath = getIcon(item.href, role);

        return (
          <Link
            key={item.href}
            href={item.href}
            className={cn(
              "group flex items-center gap-2.5 rounded-lg px-3 py-2 text-small font-medium transition-all duration-150",
              isActive
                ? "bg-primary-soft text-primary"
                : "text-ink-soft hover:bg-neutral-soft hover:text-ink",
            )}
          >
            {isActive ? (
              <span className="absolute left-0 h-6 w-1 rounded-full bg-primary" />
            ) : null}
            {iconPath ? (
              <svg
                className={cn(
                  "size-4 shrink-0 transition-colors",
                  isActive ? "text-primary" : "text-ink-faint group-hover:text-ink-soft",
                )}
                fill="none"
                viewBox="0 0 24 24"
                strokeWidth={1.5}
                stroke="currentColor"
              >
                <path strokeLinecap="round" strokeLinejoin="round" d={iconPath} />
              </svg>
            ) : null}
            {item.label}
          </Link>
        );
      })}
    </nav>
  );
}
